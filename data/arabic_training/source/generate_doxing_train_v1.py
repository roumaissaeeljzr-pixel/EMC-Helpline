VALID_BOUNDARY_INTENTS={
    "Cyberharcèlement","Sextorsion","Piratage de compte",
    "Divulgation de données personnelles (Doxing)","Conservation des preuves",
    "Informations juridiques","Usurpation d'identité",
    "Diffusion non consentie d'images","Signalement",
    "Situation d'urgence","Accompagnement de la victime"
}
PATTERN=re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06DC\u06DF-\u06E8\u06EA-\u06ED]")

def normalize_arabic_text(text):
    text=unicodedata.normalize("NFC",text)
    text=PATTERN.sub("",text)
    text=re.sub(r"[إأآا]","ا",text)
    text=re.sub(r"ى","ي",text)
    text=re.sub(r"ة","ه",text)
    text=re.sub(r"[^\w\s]","",text)
    return re.sub(r"\s+"," ",text).strip().lower()

def tokenize(text): return set(normalize_arabic_text(text).split())
def word_count(text): return len(text.split())

def validate(entries):
    assert len(entries)==100
    assert len({e["id"] for e in entries})==100
    assert all(e["label"]=="Divulgation de données personnelles (Doxing)" for e in entries)
    fields={"id","text","label","style","boundary_with","scenario_group"}
    assert all(set(e.keys())==fields for e in entries)
    assert Counter(e["style"] for e in entries)==Counter(EXPECTED_STYLES)
    assert Counter(e["boundary_with"] for e in entries if e["style"]=="boundary")==Counter(EXPECTED_BOUNDARIES)
    assert all(e["boundary_with"] is None for e in entries if e["style"]!="boundary")
    assert all(e["boundary_with"] in VALID_BOUNDARY_INTENTS for e in entries if e["boundary_with"] is not None)

def main():
    validate(ENTRIES)
    groups=defaultdict(list)
    for e in ENTRIES: groups[e["scenario_group"]].append(e["id"])
    sizes=[len(v) for v in groups.values()]
    dist=Counter(sizes)
    assert max(sizes)<=3

    exact=len(ENTRIES)-len({e["text"] for e in ENTRIES})
    normalized=len(ENTRIES)-len({normalize_arabic_text(e["text"]) for e in ENTRIES})

    ids=[e["id"] for e in ENTRIES]
    toks={e["id"]:tokenize(e["text"]) for e in ENTRIES}
    jac=[]
    for i in range(len(ids)):
        for j in range(i+1,len(ids)):
            a,b=toks[ids[i]],toks[ids[j]]
            score=len(a&b)/len(a|b) if (a|b) else 0
            if score>=0.50: jac.append((ids[i],ids[j],round(score,3)))

    short=sum(word_count(e["text"])<15 for e in ENTRIES)
    medium=sum(15<=word_count(e["text"])<=30 for e in ENTRIES)
    long_=sum(word_count(e["text"])>30 for e in ENTRIES)

    OUTPUT_PATH.parent.mkdir(parents=True,exist_ok=True)
    OUTPUT_PATH.write_text(json.dumps(ENTRIES,ensure_ascii=False,indent=2),encoding="utf-8")

    print(f"Fichier écrit : {OUTPUT_PATH}")
    print(f"Total : {len(ENTRIES)}")
    print()
    print("=== STYLES ===")
    for k,v in Counter(e["style"] for e in ENTRIES).items(): print(f"  {k:<12} : {v}")
    print()
    print("=== BOUNDARY_WITH ===")
    for k,v in Counter(e["boundary_with"] for e in ENTRIES if e["style"]=="boundary").items(): print(f"  {k} : {v}")
    print()
    print("=== LONGUEUR ===")
    print(f"  courtes (<15 mots) : {short}")
    print(f"  moyennes (15-30)   : {medium}")
    print(f"  longues (>30)      : {long_}")
    print()
    print("=== SCENARIO_GROUP ===")
    print(f"  groupes uniques : {len(groups)}")
    print(f"  taille 1 : {dist.get(1,0)}")
    print(f"  taille 2 : {dist.get(2,0)}")
    print(f"  taille 3 : {dist.get(3,0)}")
    print(f"  min/moy/max : {min(sizes)} / {round(sum(sizes)/len(sizes),2)} / {max(sizes)}")
    print()
    print("=== SIMILARITÉ INTERNE ===")
    print("Doublons exacts :",exact)
    print("Doublons normalisés :",normalized)
    print("Paires Jaccard >= 0.50 :",len(jac))
    for a,b,s in jac: print(f"  {a} <-> {b} : {s}")

if __name__=="__main__":
    main()